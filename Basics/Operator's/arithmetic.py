# ============================================
# 🔢 Arithmetic Operators in Python
# ============================================

# Basic Arithmetic Operators
print("===== Basic Arithmetic =====")

addition = 10 + 5
print("Addition (10 + 5):", addition)

subtraction = 10 - 5
print("Subtraction (10 - 5):", subtraction)

multiplication = 10 * 5
print("Multiplication (10 * 5):", multiplication)

division = 10 / 3
print("Division (10 / 3):", division)

modulus = 10 % 3
print("Modulus - Remainder (10 % 3):", modulus)

power = 2 ** 3
print("Power (2 ** 3):", power)

floor_division = 10 // 3
print("Floor Division (10 // 3):", floor_division)

# String with Arithmetic
print("\n===== String with Arithmetic =====")
print("Hi" * 3)

# Shortcut Assignment Operators
print("\n===== Shortcut Operators =====")

x = 10
x += 5
print("x += 5 →", x)

x = 10
x -= 5
print("x -= 5 →", x)

x = 10
x *= 5
print("x *= 5 →", x)

x = 10
x /= 5
print("x /= 5 →", x)

x = 10
x %= 3
print("x %= 3 →", x)

x = 2
x **= 3
print("x **= 3 →", x)

x = 10
x //= 3
print("x //= 3 →", x)
