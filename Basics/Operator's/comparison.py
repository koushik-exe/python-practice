# ============================================
# ⚖️ Comparison Operators in Python
# ============================================
# Comparison operators always return True or False
# = means assign | == means compare

print("===== Comparison Operators =====")

x = 10
y = 10
z = 5

print("x == y →", x == y)
print("x == z →", x == z)
print("x != z →", x != z)
print("x > z  →", x > z)
print("x < z  →", x < z)
print("x >= y →", x >= y)
print("x <= z →", x <= z)

# Assignment vs Comparison
print("\n===== Assignment vs Comparison =====")
name = "Koushik"          # assigning
print(name == "Koushik")  # comparing → True
print(name == "Ravi")     # comparing → False
